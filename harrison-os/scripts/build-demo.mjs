#!/usr/bin/env node
// Builds the in-browser preview into ../docs/harrison-os-demo/ (served by the repository's existing GitHub
// Pages site, which publishes docs/ from main). The preview is the real public/ app and the real src/ Worker
// code, copied unchanged, plus demo/ (boot, D1-on-SQLite-WASM adapter, banner). Fictional data only; no
// network calls except loading these files. Run: node scripts/build-demo.mjs
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, '..', 'docs', 'harrison-os-demo');
const SQLITE = join(ROOT, 'node_modules', '@sqlite.org', 'sqlite-wasm', 'dist');

let revision = 'unknown';
try {
  revision = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim();
  if (execSync('git status --porcelain -- .', { cwd: ROOT }).toString().trim()) revision += '+local';
} catch {
  /* not a git checkout */
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'sqlite'), { recursive: true });
cpSync(join(ROOT, 'src'), join(OUT, 'src'), { recursive: true });
cpSync(join(ROOT, 'public'), join(OUT, 'public'), { recursive: true, filter: (p) => !p.endsWith('index.html') && !p.endsWith('sw.js') });
cpSync(join(ROOT, 'migrations'), join(OUT, 'migrations'), { recursive: true });
for (const f of ['boot.js', 'd1-wasm.js', 'demo.css']) cpSync(join(ROOT, 'demo', f), join(OUT, f));
// .js (not .mjs) so every static host serves it with a JavaScript MIME type.
cpSync(join(SQLITE, 'index.mjs'), join(OUT, 'sqlite', 'sqlite3.js'));
cpSync(join(SQLITE, 'sqlite3.wasm'), join(OUT, 'sqlite', 'sqlite3.wasm'));
writeFileSync(join(OUT, 'sqlite', 'NOTICE.txt'), 'SQLite (public domain) WebAssembly build from the @sqlite.org/sqlite-wasm npm package (Apache-2.0 JS wrapper). https://sqlite.org/wasm\n');

const migrations = readdirSync(join(ROOT, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
writeFileSync(join(OUT, 'manifest.js'), `// Generated by scripts/build-demo.mjs.\nexport const REVISION = ${JSON.stringify(revision)};\nexport const MIGRATIONS = ${JSON.stringify(migrations)};\n`);

let html = readFileSync(join(ROOT, 'public', 'index.html'), 'utf8');
const swap = (from, to) => {
  if (!html.includes(from)) throw new Error(`build-demo: index.html no longer contains ${from}`);
  html = html.split(from).join(to);
};
swap("script-src 'self'", "script-src 'self' 'wasm-unsafe-eval'");
swap('<script type="module" src="/app.js"></script>', '<script type="module" src="./boot.js"></script>');
swap('<link rel="stylesheet" href="/styles.css">', '<link rel="stylesheet" href="./public/styles.css">\n  <link rel="stylesheet" href="./demo.css">');
swap('href="/views/', 'href="./public/views/');
swap('href="/icons/', 'href="./public/icons/');
html = html.replace(/\s*<link rel="manifest"[^>]*>/, '');
html = html.replace('<title>Harrison OS</title>', '<title>Harrison OS preview</title>\n  <meta name="robots" content="noindex">');
swap('<body>', `<body>\n${readFileSync(join(ROOT, 'demo', 'banner.html'), 'utf8')}`);
writeFileSync(join(OUT, 'index.html'), html);
console.log(`build-demo: wrote ${OUT} (revision ${revision}, ${migrations.length} migrations)`);
